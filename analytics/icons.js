function pie(slices,size,labels){
  let cum=0; const r=size/2-2,cx=size/2,cy=size/2;
  const total=slices.reduce((a,s)=>a+s.v,0);
  const paths=slices.map(s=>{
    const a1=cum/total*2*Math.PI; cum+=s.v; const a2=cum/total*2*Math.PI;
    const la=(a2-a1)>Math.PI?1:0;
    const mid=(a1+a2)/2;
    return {...s,d:`M ${cx} ${cy} L ${cx+r*Math.sin(a1)} ${cy-r*Math.cos(a1)} A ${r} ${r} 0 ${la} 1 ${cx+r*Math.sin(a2)} ${cy-r*Math.cos(a2)} Z`,mid};
  });
  return '<svg width="'+size+'" height="'+size+'" viewBox="0 0 '+size+' '+size+'">'
   +paths.map(p=>'<path d="'+p.d+'" fill="'+p.c+'" stroke="#fff" stroke-width="1"/>').join("")
   +(labels!==false?paths.filter(p=>p.v/total>0.045).map(p=>'<text x="'+(cx+r*0.62*Math.sin(p.mid))+'" y="'+(cy-r*0.62*Math.cos(p.mid)+3)+'" font-size="9" fill="#fff" text-anchor="middle">'+p.l2+'</text>').join(""):"")
   +'</svg>';
}
